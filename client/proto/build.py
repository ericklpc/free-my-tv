#!/usr/bin/env python3
"""Builds the player prototype into out/proto/ (open index.html in a browser), or serves it with --serve.

The TMDB key (art and Brazil's charts), the Stremio key (the catalogs of the account's addons) and the AIOStreams
link (real streams, in the Fire TV app) go in, so keep the build to yourself. Without the AIOStreams link, or in a
browser, the streams are the sample ones and playback is simulated. Keys: arrows, Enter (OK), Esc (Back), M (Menu: sources), P (play/pause), F/R (±5 min).
"""
import http.server
import json
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import webapp  # noqa: E402


def build(out_dir):
    path = os.path.join(ROOT, 'config.properties')
    cfg = webapp.read_config(path) if os.path.exists(path) else {}
    key = cfg.get('tmdbKey', '')
    # aiostreams_url (your AIOStreams manifest link) turns on the real streams in the Fire TV app.
    # trakt_client_id / trakt_client_secret (your app at trakt.tv/oauth/applications) turn on Trakt's scrobble.
    extra = {'aiostreams_url': '', 'trakt_client_id': '', 'trakt_client_secret': ''}
    if os.path.exists(path):
        for line in open(path, encoding='utf-8'):
            k = line.split('=', 1)[0].strip()
            if k in extra and '=' in line:
                extra[k] = line.split('=', 1)[1].strip().strip('"')
    aio = extra['aiostreams_url']
    # This week's picks from client/curation/curate.py, when it has run.
    picks = None
    pj = os.path.join(ROOT, 'client', 'curation', 'out', 'picks.json')
    if os.path.exists(pj):
        with open(pj, encoding='utf-8') as f:
            picks = json.load(f)
    if os.path.isdir(out_dir):
        shutil.rmtree(out_dir)
    os.makedirs(os.path.join(out_dir, 'fonts'))
    for name in os.listdir(HERE):
        if name.endswith(('.html', '.css', '.js')):
            shutil.copy(os.path.join(HERE, name), out_dir)
    with open(os.path.join(out_dir, 'config.js'), 'w', encoding='utf-8') as f:
        f.write('/* Generated by client/proto/build.py. */\nwindow.CONFIG = %s;\n' % json.dumps({'tmdbKey': key, 'stremioAuthKey': cfg.get('stremioAuthKey', ''), 'aioUrl': aio,
                                                                                      'traktId': extra['trakt_client_id'], 'traktSecret': extra['trakt_client_secret'],
                                                                                      'picks': picks}))
    for name in ('InterVariable.ttf', 'OFL.txt'):
        shutil.copy(os.path.join(ROOT, 'app', 'assets', 'fonts', name), os.path.join(out_dir, 'fonts'))
    return key


if __name__ == '__main__':
    out = os.path.join(ROOT, 'out', 'proto')
    if '--out' in sys.argv:
        out = os.path.abspath(sys.argv[sys.argv.index('--out') + 1])
    key = build(out)
    print('Built %s (%s)' % (os.path.relpath(out, ROOT), 'TMDB art' if key else 'no TMDB key: gradients instead of art'))
    if '--serve' in sys.argv:
        port = 8766
        os.chdir(out)
        print('Open http://127.0.0.1:%d' % port)
        http.server.ThreadingHTTPServer(('127.0.0.1', port), http.server.SimpleHTTPRequestHandler).serve_forever()
